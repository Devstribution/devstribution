"""Refreshes the data the dependency check bundles (crates/devstribution-core/data/):

- `pypi-malicious.txt`: PyPI packages reported as malicious in OSV (`MAL-` entries, from the
  OpenSSF malicious-packages project), with the versions affected or `*` for all of them;
- `pypi-popular.txt`: the most downloaded PyPI packages (hugovk/top-pypi-packages), which
  typosquats imitate.

The launcher and `pack` read these offline, so a check sends nothing anywhere. Run it before a
release:  python scripts/update_dep_data.py
"""

import datetime
import io
import json
import re
import sys
import urllib.request
import zipfile
from pathlib import Path

OSV_PYPI = "https://osv-vulnerabilities.storage.googleapis.com/PyPI/all.zip"
TOP_PYPI = "https://hugovk.dev/top-pypi-packages/top-pypi-packages.min.json"
POPULAR = 15000
DATA = Path(__file__).resolve().parent.parent / "crates" / "devstribution-core" / "data"


def normalize(name: str) -> str:
    """PEP 503: lowercase, runs of `-`, `_` and `.` become one `-`."""
    return re.sub(r"[-_.]+", "-", name).lower()


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=120) as response:
        return response.read()


def malicious() -> dict:
    """name -> set of versions, or None when every version is affected."""
    found: dict = {}
    with zipfile.ZipFile(io.BytesIO(fetch(OSV_PYPI))) as archive:
        for entry in archive.namelist():
            if not entry.startswith("MAL-"):
                continue
            record = json.loads(archive.read(entry))
            if record.get("withdrawn"):
                continue
            for affected in record.get("affected", []):
                package = affected.get("package", {})
                if package.get("ecosystem") != "PyPI" or not package.get("name"):
                    continue
                name = normalize(package["name"])
                versions = set(affected.get("versions") or [])
                every = any(
                    any(e.get("introduced") == "0" for e in r.get("events", []))
                    and not any("fixed" in e or "last_affected" in e for e in r.get("events", []))
                    for r in affected.get("ranges", [])
                )
                if every or not versions:
                    found[name] = None
                elif found.get(name, set()) is not None:
                    found[name] = found.get(name, set()) | versions
    return found


def main() -> int:
    DATA.mkdir(parents=True, exist_ok=True)
    today = datetime.date.today().isoformat()

    bad = malicious()
    lines = [
        f"# PyPI packages reported as malicious (OSV MAL- entries), {today}. Generated by",
        "# scripts/update_dep_data.py: <name> TAB <affected versions, comma-separated, or *>",
    ]
    for name in sorted(bad):
        versions = bad[name]
        lines.append(f"{name}\t{'*' if versions is None else ','.join(sorted(versions))}")
    (DATA / "pypi-malicious.txt").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    rows = json.loads(fetch(TOP_PYPI))["rows"][:POPULAR]
    lines = [
        f"# The {POPULAR} most downloaded PyPI packages (hugovk/top-pypi-packages), {today}.",
        "# Generated by scripts/update_dep_data.py; most downloaded first.",
    ]
    lines += [normalize(row["project"]) for row in rows]
    (DATA / "pypi-popular.txt").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    print(f"{len(bad)} malicious packages, {len(rows)} popular packages -> {DATA}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
