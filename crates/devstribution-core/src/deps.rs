//! Checks on the packages an app installs, read from its `uv.lock` without downloading anything:
//!
//! - packages reported as malicious on PyPI (OSV `MAL-` entries, from the OpenSSF
//!   malicious-packages project), the whole package or the locked version;
//! - names one edit away from a popular package (`reqeusts`), the usual typosquat.
//!
//! The lists are bundled (`data/`, refreshed by `scripts/update_dep_data.py` before a release),
//! so the check sends nothing anywhere and works offline; it knows what was reported up to the
//! date [`list_date`] returns. The top 15,000 packages count as known, so only names outside
//! them are compared with the top 1,000 (about 1% of the packages ranked 5,000 to 15,000 would
//! match, nearly all legitimately).

use std::collections::{HashMap, HashSet};
use std::sync::OnceLock;

const MALICIOUS: &str = include_str!("../data/pypi-malicious.txt");
const POPULAR: &str = include_str!("../data/pypi-popular.txt");

/// Names a typosquat imitates: only the most downloaded are worth imitating, and a short list
/// keeps unrelated small packages from matching by chance.
const SQUAT_TARGETS: usize = 1000;
/// Shorter names are one edit away from too many others (`six`, `rich`, `toml`).
const SQUAT_MIN_LEN: usize = 5;

/// One package in the lockfile that the check flags.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DepHit {
    pub kind: DepHitKind,
    pub name: String,
    pub version: String,
    /// 1-based line of the package's `name = "…"` in `uv.lock`.
    pub line: Option<u32>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DepHitKind {
    /// The locked version (or every version) was reported as malicious.
    Malicious,
    /// Other versions were reported as malicious (a hijacked project); this one was not.
    OtherVersionMalicious,
    /// Not a popular package, but one edit away from this one.
    LooksLike(String),
}

/// What [`check`] looked at.
#[derive(Debug, Clone, Default)]
pub struct DepCheck {
    pub packages: usize,
    pub hits: Vec<DepHit>,
}

/// The date of the bundled lists, from their first line.
pub fn list_date() -> &'static str {
    static DATE: OnceLock<String> = OnceLock::new();
    DATE.get_or_init(|| {
        MALICIOUS
            .lines()
            .next()
            .and_then(|l| l.rsplit(", ").next())
            .map(|d| d.trim_end_matches(". Generated by").to_string())
            .unwrap_or_default()
    })
}

/// The packages in `uv.lock` (except the app itself), checked against the bundled lists. A
/// lockfile that does not parse gives no hits: the install-time lockfile checks refuse it.
pub fn check(lock: &str) -> DepCheck {
    let Ok(raw) = toml::from_str::<RawLock>(lock) else {
        return DepCheck::default();
    };
    let mut out = DepCheck::default();
    for p in raw.package {
        if p.source.contains_key("virtual") || p.source.contains_key("editable") {
            continue;
        }
        out.packages += 1;
        let name = normalize(&p.name);
        let version = p.version.unwrap_or_default();
        let line = lock
            .lines()
            .position(|l| l.trim() == format!("name = \"{}\"", p.name))
            .map(|i| i as u32 + 1);
        let hit = |kind| DepHit {
            kind,
            name: name.clone(),
            version: version.clone(),
            line,
        };
        match malicious().get(name.as_str()) {
            Some(None) => out.hits.push(hit(DepHitKind::Malicious)),
            Some(Some(versions)) if versions.contains(version.as_str()) => {
                out.hits.push(hit(DepHitKind::Malicious))
            }
            Some(Some(_)) => out.hits.push(hit(DepHitKind::OtherVersionMalicious)),
            None => {}
        }
        if let Some(target) = looks_like_popular(&name) {
            out.hits
                .push(hit(DepHitKind::LooksLike(target.to_string())));
        }
    }
    out
}

/// Every package in `uv.lock` besides the app itself, by normalized name, with its locked
/// version. A lockfile that does not parse gives none.
pub fn packages(lock: &str) -> std::collections::BTreeMap<String, String> {
    let Ok(raw) = toml::from_str::<RawLock>(lock) else {
        return Default::default();
    };
    raw.package
        .into_iter()
        .filter(|p| !p.source.contains_key("virtual") && !p.source.contains_key("editable"))
        .map(|p| (normalize(&p.name), p.version.unwrap_or_default()))
        .collect()
}

/// PEP 503 name: lowercase, runs of `-`, `_` and `.` become one `-`.
pub fn normalize(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut sep = false;
    for c in name.chars() {
        if matches!(c, '-' | '_' | '.') {
            sep = true;
        } else {
            if sep && !out.is_empty() {
                out.push('-');
            }
            sep = false;
            out.extend(c.to_lowercase());
        }
    }
    out
}

/// A popular package `name` imitates, if `name` is not popular itself.
fn looks_like_popular(name: &str) -> Option<&'static str> {
    let (all, targets) = popular();
    if all.contains(name) {
        return None;
    }
    let without =
        |s: &str, drop: fn(&char) -> bool| s.chars().filter(|c| !drop(c)).collect::<String>();
    let bare = without(name, |c| *c == '-');
    let letters = without(name, char::is_ascii_digit);
    targets.iter().copied().find(|target| {
        target.len() >= SQUAT_MIN_LEN
            // A version number added or dropped (`elasticsearch8`, `gitdb2`) is how real
            // packages are named too.
            && letters != without(target, char::is_ascii_digit)
            && (one_edit_apart(name, target) || bare == without(target, |c| *c == '-'))
    })
}

/// Whether `a` becomes `b` with one insertion, deletion, substitution or swap of neighbours.
fn one_edit_apart(a: &str, b: &str) -> bool {
    let (a, b): (Vec<char>, Vec<char>) = (a.chars().collect(), b.chars().collect());
    if a == b || a.len().abs_diff(b.len()) > 1 {
        return false;
    }
    let prefix = a.iter().zip(&b).take_while(|(x, y)| x == y).count();
    let (ra, rb) = (&a[prefix..], &b[prefix..]);
    match ra.len().cmp(&rb.len()) {
        std::cmp::Ordering::Equal => {
            ra[1..] == rb[1..]
                || (ra.len() >= 2 && ra[0] == rb[1] && ra[1] == rb[0] && ra[2..] == rb[2..])
        }
        std::cmp::Ordering::Less => ra == &rb[1..],
        std::cmp::Ordering::Greater => &ra[1..] == rb,
    }
}

/// Name → `None` when every version is malicious, else the affected versions.
fn malicious() -> &'static HashMap<&'static str, Option<HashSet<&'static str>>> {
    static MAP: OnceLock<HashMap<&'static str, Option<HashSet<&'static str>>>> = OnceLock::new();
    MAP.get_or_init(|| {
        data_lines(MALICIOUS)
            .filter_map(|l| l.split_once('\t'))
            .map(|(name, versions)| {
                let versions = (versions != "*").then(|| versions.split(',').collect());
                (name, versions)
            })
            .collect()
    })
}

/// Every popular name, and the most popular ones in download order.
fn popular() -> &'static (HashSet<&'static str>, Vec<&'static str>) {
    static LISTS: OnceLock<(HashSet<&'static str>, Vec<&'static str>)> = OnceLock::new();
    LISTS.get_or_init(|| {
        let names: Vec<&str> = data_lines(POPULAR).collect();
        let targets = names.iter().copied().take(SQUAT_TARGETS).collect();
        (names.into_iter().collect(), targets)
    })
}

fn data_lines(data: &'static str) -> impl Iterator<Item = &'static str> {
    data.lines()
        .map(str::trim_end)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
}

#[derive(serde::Deserialize)]
struct RawLock {
    #[serde(default)]
    package: Vec<RawPackage>,
}

#[derive(serde::Deserialize)]
struct RawPackage {
    name: String,
    version: Option<String>,
    #[serde(default)]
    source: HashMap<String, toml::Value>,
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lock(packages: &[(&str, &str)]) -> String {
        let mut s = String::from(
            "version = 1\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\nsource = { virtual = \".\" }\n",
        );
        for (name, version) in packages {
            s.push_str(&format!(
                "\n[[package]]\nname = \"{name}\"\nversion = \"{version}\"\nsource = {{ registry = \"https://pypi.org/simple\" }}\n"
            ));
        }
        s
    }

    #[test]
    fn ordinary_dependencies_pass() {
        let c = check(&lock(&[
            ("pandas", "2.2.3"),
            ("openpyxl", "3.1.5"),
            ("requests", "2.32.3"),
        ]));
        assert_eq!(c.packages, 3);
        assert!(c.hits.is_empty(), "{:?}", c.hits);
    }

    #[test]
    fn a_malicious_package_is_flagged_with_its_line() {
        // In the list for every version.
        let name = malicious()
            .iter()
            .find(|(_, v)| v.is_none())
            .map(|(n, _)| *n)
            .unwrap();
        let text = lock(&[("pandas", "2.2.3"), (name, "1.0.0")]);
        let c = check(&text);
        let hit = c
            .hits
            .iter()
            .find(|h| h.kind == DepHitKind::Malicious)
            .unwrap();
        assert_eq!(hit.name, name);
        let line = text.lines().nth(hit.line.unwrap() as usize - 1).unwrap();
        assert_eq!(line, format!("name = \"{name}\""));
    }

    #[test]
    fn a_hijacked_release_is_flagged_but_not_the_others() {
        // num2words 0.5.15 and 0.5.16 were published by an attacker; 0.5.14 is the real one.
        let bad = check(&lock(&[("num2words", "0.5.15")]));
        assert_eq!(bad.hits[0].kind, DepHitKind::Malicious);
        let good = check(&lock(&[("num2words", "0.5.14")]));
        assert_eq!(good.hits[0].kind, DepHitKind::OtherVersionMalicious);
    }

    #[test]
    fn typosquats_of_popular_packages_are_flagged() {
        for (squat, target) in [
            ("reqeusts", "requests"),
            ("requets", "requests"),
            ("numpyy", "numpy"),
            ("open-pyxl", "openpyxl"),
        ] {
            let c = check(&lock(&[(squat, "1.0")]));
            assert!(
                c.hits
                    .iter()
                    .any(|h| h.kind == DepHitKind::LooksLike(target.into())),
                "{squat}: {:?}",
                c.hits
            );
        }
        // Popular packages close to each other are not flagged, nor a version number in a name.
        assert!(
            check(&lock(&[("pyyaml", "6.0"), ("pyaml", "24.0")]))
                .hits
                .is_empty()
        );
        assert!(check(&lock(&[("matplotlib9", "1.0")])).hits.is_empty());
    }

    #[test]
    fn edit_distance_one() {
        assert!(one_edit_apart("requests", "reqeusts"));
        assert!(one_edit_apart("requests", "request"));
        assert!(one_edit_apart("requests", "requestss"));
        assert!(one_edit_apart("requests", "requezts"));
        assert!(!one_edit_apart("requests", "requests"));
        assert!(!one_edit_apart("requests", "rqeuesst"));
    }

    #[test]
    fn names_are_normalized() {
        assert_eq!(normalize("Typing_Extensions"), "typing-extensions");
        assert_eq!(normalize("zope.interface"), "zope-interface");
        assert_eq!(normalize("a__-b"), "a-b");
    }

    #[test]
    fn the_lists_are_loaded() {
        assert!(malicious().len() > 1000);
        assert!(popular().0.contains("requests"));
        assert!(list_date().starts_with("20"), "{}", list_date());
    }
}
