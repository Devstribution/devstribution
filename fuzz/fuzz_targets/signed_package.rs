//! Correctly signed packages with hostile contents: a signature proves who made a package, not
//! that it is harmless, so everything after the signature check sees an attacker's bytes too.
//! Random zips never get that far, so this target builds and signs them.
#![no_main]

use std::io::Write;
use std::sync::OnceLock;

use arbitrary::Arbitrary;
use devstribution_core::files::FilesList;
use devstribution_core::manifest::Manifest;
use devstribution_core::signing::{Signer, TrustedComment, generate_keys, public_key_file};
use devstribution_core::{FILES_LIST, FILES_PUBLIC_KEY, FILES_SIGNATURE};
use devstribution_fuzz::extract_and_check;
use libfuzzer_sys::fuzz_target;
use zip::write::SimpleFileOptions;

const PYPROJECT: &str = include_str!("../../examples/hello-gui/pyproject.toml");
const LOCK: &str = include_str!("../../examples/hello-gui/uv.lock");
const MAIN: &str = include_str!("../../examples/hello-gui/main.py");

#[derive(Arbitrary, Debug)]
struct Input {
    /// Replace the valid manifest, or the valid lockfile.
    pyproject: Option<String>,
    lock: Option<String>,
    /// More entries; the flag puts one in the signed list, when the list takes it.
    entries: Vec<(Name, Vec<u8>, bool)>,
}

/// Generated bytes rarely spell a path that matters, and this target is too slow to wait for them,
/// so the known tricks are one choice away.
#[derive(Arbitrary, Debug)]
enum Name {
    Known(u8),
    Any(String),
}

const KNOWN_NAMES: &[&str] = &[
    "../x",
    "a/../../x",
    r"..\x",
    r"a\..\..\x",
    "/x",
    "//server/share/x",
    "C:/x",
    r"C:\x",
    "C:x",
    "./x",
    "a//x",
    "CON",
    "nul.txt",
    "a/COM1",
    "x.",
    "x ",
    "x:stream",
    "A/x",
    "a/y",
    "a",
    "a/",
    "PYPROJECT.TOML",
    "pyproject.toml",
    "uv.lock",
    "main.py",
    "FILES.sha256",
    "FILES.sha256.minisig",
    "\u{212a}elvin",
    "kelvin",
];

impl Name {
    fn text(&self) -> &str {
        match self {
            Name::Known(i) => KNOWN_NAMES[*i as usize % KNOWN_NAMES.len()],
            Name::Any(text) => text,
        }
    }
}

fn signer() -> &'static Signer {
    static SIGNER: OnceLock<Signer> = OnceLock::new();
    SIGNER.get_or_init(|| {
        let keys = generate_keys("fuzz", None).unwrap();
        Signer::from_unencrypted(&keys.secret_key).unwrap().unwrap()
    })
}

fuzz_target!(|input: Input| {
    let pyproject = input.pyproject.as_deref().unwrap_or(PYPROJECT);
    let lock = input.lock.as_deref().unwrap_or(LOCK);
    let mut entries: Vec<(&str, &[u8], bool)> = vec![
        ("pyproject.toml", pyproject.as_bytes(), true),
        ("uv.lock", lock.as_bytes(), true),
        ("main.py", MAIN.as_bytes(), true),
    ];
    for (name, data, listed) in &input.entries {
        entries.push((name.text(), data, *listed));
    }

    let mut list = FilesList::new();
    for (name, data, listed) in &entries {
        if *listed {
            let _ = list.insert(name, data);
        }
    }
    let list_text = list.to_canonical_string();
    // The comment must name a valid app: a manifest that does not parse signs as the example.
    let manifest = Manifest::parse(pyproject)
        .or_else(|_| Manifest::parse(PYPROJECT))
        .unwrap();
    let comment = TrustedComment {
        id: manifest.id,
        version: manifest.version,
        schema: manifest.schema_version,
    };
    let signature = signer().sign(list_text.as_bytes(), &comment).unwrap();
    let key = public_key_file(signer().public_key(), "fuzz");

    let work = tempfile::tempdir().unwrap();
    let package = work.path().join("in.dsapp");
    let file = std::fs::File::create(&package).unwrap();
    let mut zip = zip::ZipWriter::new(file);
    let options = SimpleFileOptions::default();
    let mut add = |name: &str, data: &[u8]| {
        // The writer refuses a name twice; the reader's own refusal has tests of its own.
        if zip.start_file(name, options).is_ok() {
            zip.write_all(data).unwrap();
        }
    };
    add(FILES_LIST, list_text.as_bytes());
    add(FILES_SIGNATURE, signature.as_bytes());
    add(FILES_PUBLIC_KEY, key.as_bytes());
    for (name, data, _) in &entries {
        add(name, data);
    }
    zip.finish().unwrap();

    extract_and_check(work.path(), &package);
});
